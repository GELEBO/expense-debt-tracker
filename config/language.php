<?php

/*
|--------------------------------------------------------------------------
| Language System
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| Available Languages
|--------------------------------------------------------------------------
*/

$available_languages = [
    'en',
    'am'
];

/*
|--------------------------------------------------------------------------
| Select Language
|--------------------------------------------------------------------------
*/

if (isset($_GET['lang']) && in_array($_GET['lang'], $available_languages, true)) {
    $_SESSION['language'] = $_GET['lang'];
}

/*
|--------------------------------------------------------------------------
| Default Language
|--------------------------------------------------------------------------
*/

$current_language = $_SESSION['language'] ?? 'en';

/*
|--------------------------------------------------------------------------
| Load Translation File
|--------------------------------------------------------------------------
*/

$translations = require __DIR__ . '/../languages/' . $current_language . '.php';

/*
|--------------------------------------------------------------------------
| Translation Function
|--------------------------------------------------------------------------
*/

function __($key)
{
    global $translations;

    return $translations[$key] ?? $key;
}